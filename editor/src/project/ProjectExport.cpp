// The project's own directories worth shipping.
//
// `scenes` is here for the .scn sources as well as the cooked maps, which looks
// wasteful and is not: they are small, and a shipped game that still carries
// its scenes can be opened in the editor by whoever received it. That is how a
// modding story starts, and dropping them buys back kilobytes.
//
// Deliberately absent: `.raven`, which is per-user working state -- the cooked
// output is written fresh by the export, not copied from whatever the last
// playtest happened to leave there.
const std::vector<std::string>& projectDirectories()
{
    static const std::vector<std::string> kDirs = {
        "scenes", "scripts", "materials", "textures", "meshes", "config",
        "audio",  "fonts",   "shaders",   "ui",
    };
    return kDirs;
}

std::string executableNameFrom(const std::string& projectName)
{
    std::string name;
    for (const char c : projectName) {
        if (std::isalnum(static_cast<unsigned char>(c)))
            name += char(std::tolower(static_cast<unsigned char>(c)));
        else if (!name.empty() && name.back() != '-')
            name += '-';
    }
    while (!name.empty() && name.back() == '-')
        name.pop_back();
    return name.empty() ? "game" : name;
}

bool directoryIsEmpty(const fs::path& dir)
{
    std::error_code ec;
    if (!fs::exists(dir, ec))
        return true;
    return fs::directory_iterator(dir, ec) == fs::directory_iterator();
}

// Copies a directory tree, counting what it moved. Missing sources are not an
// error: a project with no textures/ is a project that has not needed one, and
// refusing to export it would be absurd.
void copyTree(const fs::path& from, const fs::path& to, ExportReport& report)
{
    std::error_code ec;
    if (!fs::is_directory(from, ec))
        return;
    // Created even when the source is empty. A project's assets.toml declares
    // its resource directories whether or not it has put anything in them yet,
    // and a mounted pack that names a directory which is not there warns on
    // every launch of the shipped game.
    fs::create_directories(to, ec);

    for (fs::recursive_directory_iterator it(from, ec), end; it != end;
         it.increment(ec)) {
        if (ec)
            break;
        const fs::path relative = fs::relative(it->path(), from, ec);
        if (ec)
            continue;
        const fs::path target = to / relative;
        if (it->is_directory()) {
            fs::create_directories(target, ec);
            continue;
        }
        if (!it->is_regular_file())
            continue;
        fs::create_directories(target.parent_path(), ec);
        fs::copy_file(it->path(), target,
                      fs::copy_options::overwrite_existing, ec);
        if (ec)
            continue;
        ++report.filesCopied;
        report.bytesCopied += std::size_t(fs::file_size(it->path(), ec));
    }
}

// The manifest the shipped build reads. Written rather than copied: the source
// tree's assets.toml describes a source tree, and half its resource
// directories will not exist in an export.
bool writeEngineManifest(const fs::path& assetsDir, ExportReport& report)
{
    std::ofstream out(assetsDir / "assets.toml", std::ios::trunc);
    if (!out) {
        report.error = "could not write assets.toml";
        return false;
    }
    out << "# Generated by the exporter. The engine content a shipped game\n"
           "# needs; the project's own pack is mounted over this at startup.\n"
           "schema = 1\n\n"
           "[[pack]]\n"
           "id = \"content\"\n"
           "dir = \".\"\n"
           "resources = [\n";
    // Only the directories that were actually copied, so the renderer does not
    // register a resource location that is not there.
    for (const char* dir :
         {"materials", "shaders", "compositors", "fonts", "ui", "textures",
          "textures/dungeon", "textures/props", "textures/prototype",
          "textures/surfaces", "textures/vfx", "textures/viewmodels",
          "particles/textures", "particles/textures/sheets"}) {
        std::error_code ec;
        if (fs::is_directory(assetsDir / dir, ec))
            out << "    \"" << dir << "\",\n";
    }
    out << "]\n\n[mounts]\ngame = [\"content\"]\neditor = [\"content\"]\n"
           "demo = [\"content\"]\n";
    return bool(out);
}

