std::string modelSlug(const std::string& sourcePath)
{
    return slugOf(fs::path(sourcePath).stem().string());
}

const std::vector<std::string>& textureExtensions()
{
    // Exactly what stb_image decodes -- the renderer loads every texture
    // through stbi_load (engine/src/render/rhi/Image.cpp) and has no other
    // decoder. .dds used to be here because OgreMain carried its own DDS
    // codec; that went with OGRE, so listing it now would promise a format
    // the renderer silently fails to load.
    static const std::vector<std::string> kExtensions = {
        ".png", ".jpg", ".jpeg", ".bmp", ".tga", ".psd",
        ".gif", ".hdr", ".pic",  ".pnm", ".ppm", ".pgm",
    };
    return kExtensions;
}

ModelImportResult importModelToKit(const std::string& sourcePath,
                                   const std::string& assetRoot)
{
    ModelImportResult result;

    const fs::path source = fs::absolute(sourcePath);
    std::error_code ec;
    if (!fs::is_regular_file(source, ec)) {
        result.error = "no such file: " + source.string();
        return result;
    }
    if (!eng::detail::assimpSupportsModelFile(source)) {
        result.error = "this build of Assimp cannot read " +
                       source.extension().string() + " files";
        return result;
    }

    // Source pivot: the parts are pivoted individually below, and their offsets
    // are what reassembles the model. Letting the importer centre it first
    // would fold the arrangement into the geometry and lose it.
    eng::ModelImportOptions options;
    options.pivot = eng::PivotMode::Source;

    eng::detail::ImportedModelData model;
    eng::ModelImportReport report;
    if (!eng::detail::importStaticModel(source, options, model, report)) {
        result.error = report.error.empty()
                           ? ("cannot import " + source.filename().string())
                           : report.error;
        return result;
    }
    if (model.submeshes.empty()) {
        result.error = source.filename().string() + " has no geometry";
        return result;
    }
    result.warnings = report.warnings;

    const std::string slug = modelSlug(sourcePath);
    const std::string prefix = "import_" + slug;

    const fs::path meshDir = fs::path(assetRoot) / "meshes" / "props";
    const fs::path materialDir = fs::path(assetRoot) / "materials";
    const fs::path textureDir = fs::path(assetRoot) / "textures";
    fs::create_directories(meshDir, ec);
    fs::create_directories(materialDir, ec);
    fs::create_directories(textureDir, ec);
    if (ec) {
        result.error = "cannot create import directories: " + ec.message();
        return result;
    }
    const fs::path modelDir = source.parent_path();
    // One walk for the whole import, not one per textured submesh.
    const TextureIndex textures = indexTextures(modelDir);

    Bounds modelBounds;
    for (const auto& submesh : model.submeshes)
        for (const auto& vertex : submesh.vertices)
            modelBounds.add(vertex.position);
    if (!modelBounds.valid()) {
        result.error = source.filename().string() + " has no vertices";
        return result;
    }
    const glm::vec3 modelPivot = modelBounds.bottomCentre();

    std::ostringstream block;
    block << std::fixed;
    block.precision(4);
    std::ostringstream materials;
    // Copied once per distinct source texture: two submeshes sharing a material
    // must not race to write the same file twice.
    std::vector<std::pair<std::string, std::string>> copiedTextures;

    for (std::size_t index = 0; index < model.submeshes.size(); ++index) {
        const eng::detail::ImportedModelSubmesh& submesh =
            model.submeshes[index];
        if (submesh.vertices.empty() || submesh.indices.empty())
            continue;

        const std::string partId =
            model.submeshes.size() == 1
                ? prefix
                : prefix + "_p" + std::to_string(index);
        const std::string objName = partId + ".obj";

        const Bounds partBounds = boundsOf(submesh);
        const glm::vec3 partPivot = partBounds.bottomCentre();
        const glm::vec3 size = partBounds.max - partBounds.min;

        std::string error;
        if (!writeObj(meshDir / objName, submesh, partPivot, error)) {
            result.error = error;
            return result;
        }

        // A texture beside the model gets copied in and given its own material.
        // Failing that, vertex colours if the mesh has them, and the prototype
        // surface if it has neither -- which reads as obviously unfinished
        // rather than as a black prop.
        std::string material = hasVertexColours(submesh)
                                   ? "Game/PropVertexColour"
                                   : "Engine/Psx/PrototypeSurface";
        if (!submesh.sourceTexture.empty()) {
            std::string copiedName;
            for (const auto& [authored, name] : copiedTextures)
                if (authored == submesh.sourceTexture)
                    copiedName = name;

            if (copiedName.empty()) {
                const fs::path found =
                    resolveTexture(modelDir, submesh.sourceTexture, textures);
                if (found.empty()) {
                    result.warnings.push_back(
                        "texture not found under " +
                        modelDir.filename().string() + " or its parent: " +
                        submesh.sourceTexture);
                }
                else {
                    // Prefixed with the model's slug: two models are entitled
                    // to ship a texture called "386.png", and the pack is flat.
                    copiedName = prefix + "_" + found.filename().string();
                    fs::copy_file(found, textureDir / copiedName,
                                  fs::copy_options::overwrite_existing, ec);
                    if (ec) {
                        result.warnings.push_back("could not copy " +
                                                  found.filename().string() +
                                                  ": " + ec.message());
                        ec.clear();
                        copiedName.clear();
                    }
                    else {
                        copiedTextures.emplace_back(submesh.sourceTexture,
                                                    copiedName);
                        result.textures.push_back(copiedName);
                    }
                }
            }
            if (!copiedName.empty()) {
                material = "Game/" + prefix + "/part" + std::to_string(index);
                materials << materialBlock(material, copiedName);
            }
        }

        block << "[[piece]]\n"
              << "id = \"" << partId << "\"\n"
              << "role = \""
              << (model.submeshes.size() == 1 ? "imported_model"
                                              : "imported_part")
              << "\"\n"
              << "mesh = \"meshes/props/" << objName << "\"\n"
              << "material = \"" << material << "\"\n"
              << "socket = \"prop\"\n"
              << "import_scale = 1.0\n"
              << "size = [" << size.x << ", " << size.y << ", " << size.z
              << "]\n\n";

        result.parts.push_back(
            {"kit." + partId, submesh.name, partPivot - modelPivot});
    }

    if (result.parts.empty()) {
        result.error = source.filename().string() + " has no usable submeshes";
        return result;
    }

    // The model itself, as one placeable.
    //
    // A part is a piece; the model is the group of them, and without it the
    // only trace of "these twenty-four objs are one boss" was the scene it was
    // first imported into. The group carries no mesh -- its geometry is its
    // attachments, at the offsets computed above -- and the editor unpacks
    // those into real child entities when it places one, which is what puts
    // the parts in the hierarchy where they can be moved.
    if (result.parts.size() == 1) {
        result.root = result.parts.front().prefab;
    }
    else {
        result.root = "kit." + prefix;
        const glm::vec3 modelSize = modelBounds.max - modelBounds.min;
        block << "[[piece]]\n"
              << "id = \"" << prefix << "\"\n"
              << "role = \"imported_model\"\n"
              << "socket = \"prop\"\n"
              << "import_scale = 1.0\n"
              << "size = [" << modelSize.x << ", " << modelSize.y << ", "
              << modelSize.z << "]\n"
              << "attachments = [\n";
        for (const ImportedPart& part : result.parts) {
            block << "  { prefab = \"" << part.prefab << "\", position = ["
                  << part.offset.x << ", " << part.offset.y << ", "
                  << part.offset.z << "] },\n";
        }
        block << "]\n\n";
    }

    if (report.embeddedTextures > 0)
        result.warnings.push_back(
            std::to_string(report.embeddedTextures) +
            " embedded texture(s) were not extracted -- assign a material in "
            "the Material panel");

    std::string error;
    if (materials.tellp() > 0) {
        const fs::path scriptPath = materialDir / (prefix + ".mat");
        std::ofstream script(scriptPath);
        if (!script) {
            result.error = "cannot write " + scriptPath.string();
            return result;
        }
        script << materials.str();
        if (!script) {
            result.error = "failed writing " + scriptPath.string();
            return result;
        }
        result.materialScript = scriptPath.string();
    }

    if (!rewriteCatalogBlock(fs::path(assetRoot) / "config" / "kit.toml", slug,
                             block.str(), error)) {
        result.error = error;
        return result;
    }

    result.ok = true;
    return result;
}

