std::string slugOf(std::string value)
{
    std::string out = eng::assets::canonicalToken(value);
    return out.empty() ? std::string("model") : out;
}

struct Bounds {
    glm::vec3 min{std::numeric_limits<float>::infinity()};
    glm::vec3 max{-std::numeric_limits<float>::infinity()};

    void add(const glm::vec3& point)
    {
        min = glm::min(min, point);
        max = glm::max(max, point);
    }
    bool valid() const { return min.x <= max.x; }
    // The engine's canonical placement pivot: on the ground, centred
    // horizontally. Matching it here is what keeps an imported prop standing on
    // the floor rather than half-sunk into it.
    glm::vec3 bottomCentre() const
    {
        return {(min.x + max.x) * 0.5f, min.y, (min.z + max.z) * 0.5f};
    }
};

Bounds boundsOf(const eng::detail::ImportedModelSubmesh& submesh)
{
    Bounds bounds;
    for (const auto& vertex : submesh.vertices)
        bounds.add(vertex.position);
    return bounds;
}

// True when the mesh actually carries colour. Assimp defaults every vertex to
// opaque white, and picking the vertex-colour material for a model that has
// none renders it flat white instead of showing its texture slot.
bool hasVertexColours(const eng::detail::ImportedModelSubmesh& submesh)
{
    for (const auto& vertex : submesh.vertices) {
        const glm::vec4& c = vertex.colour;
        if (c.r < 0.999f || c.g < 0.999f || c.b < 0.999f)
            return true;
    }
    return false;
}

bool writeObj(const fs::path& path,
              const eng::detail::ImportedModelSubmesh& submesh,
              const glm::vec3& pivot, std::string& error)
{
    std::ofstream stream(path);
    if (!stream) {
        error = "cannot write " + path.string();
        return false;
    }
    stream << "# generated by the editor's model importer\n";
    stream << std::fixed;
    stream.precision(6);
    for (const auto& vertex : submesh.vertices) {
        const glm::vec3 p = vertex.position - pivot;
        stream << "v " << p.x << ' ' << p.y << ' ' << p.z << ' '
               << vertex.colour.r << ' ' << vertex.colour.g << ' '
               << vertex.colour.b << ' ' << vertex.colour.a << '\n';
    }
    // V is written flipped because this renderer's OBJ path flips it again on
    // load (see ModelImport.h). Two flips is the identity; one is a texture
    // upside down, which is the classic symptom of touching only one side.
    for (const auto& vertex : submesh.vertices)
        stream << "vt " << vertex.texcoord.x << ' ' << 1.0f - vertex.texcoord.y
               << '\n';
    for (const auto& vertex : submesh.vertices)
        stream << "vn " << vertex.normal.x << ' ' << vertex.normal.y << ' '
               << vertex.normal.z << '\n';
    for (std::size_t i = 0; i + 2 < submesh.indices.size(); i += 3) {
        const uint32_t a = submesh.indices[i] + 1;
        const uint32_t b = submesh.indices[i + 1] + 1;
        const uint32_t c = submesh.indices[i + 2] + 1;
        stream << "f " << a << '/' << a << '/' << a << ' ' << b << '/' << b
               << '/' << b << ' ' << c << '/' << c << '/' << c << '\n';
    }
    return bool(stream);
}

// Every loadable image under a model's directory, indexed by how a material
// might name it.
//
// Built once per import rather than scanned per material: a model with twenty
// textured submeshes would otherwise walk the same tree twenty times.
//
// Two indices, because exporters get this wrong in two distinct ways. `byName`
// answers "a file called diffuse.png exists somewhere below here", which covers
// the very common pack layout where the model sits in source/ and its textures
// in a sibling folder. `byStem` answers "something called diffuse exists, in
// some format", which covers the equally common case of an .mtl referencing
// diffuse.tga when what actually shipped is diffuse.png.
struct TextureIndex {
    std::unordered_map<std::string, fs::path> byName;
    std::unordered_map<std::string, fs::path> byStem;
};

std::string lowered(std::string value)
{
    std::transform(value.begin(), value.end(), value.begin(),
                   [](unsigned char c) { return char(std::tolower(c)); });
    return value;
}

void indexInto(TextureIndex& index, const fs::path& root)
{
    std::error_code ec;
    if (!fs::is_directory(root, ec))
        return;
    // Bounded: pointing an import at a model inside a very large tree must not
    // hang the editor. findFiles already caps depth and count.
    ScanLimits limits;
    limits.maxFiles = 2000;
    limits.maxDepth = 6;
    for (const FileEntry& entry :
         findFiles(root.string(), textureExtensions(), limits).files) {
        const fs::path path(entry.path);
        // First match wins, and findFiles sorts by label, so which file a name
        // resolves to does not depend on directory iteration order.
        index.byName.emplace(lowered(path.filename().string()), path);
        index.byStem.emplace(lowered(path.stem().string()), path);
    }
}

TextureIndex indexTextures(const fs::path& modelDir)
{
    TextureIndex index;
    indexInto(index, modelDir);
    // Then the parent, whose own entries only fill gaps -- emplace keeps the
    // first. A texture beside the model always beats one belonging to a sibling
    // model that happened to pick the same file name.
    const fs::path parent = modelDir.parent_path();
    if (!parent.empty() && parent != modelDir)
        indexInto(index, parent);
    return index;
}

// Where a material's texture actually lives on disk.
//
// Assimp reports it as the source file spells it, which for the .mtl beside an
// OBJ is a bare "386.png" relative to the model -- not to the editor's working
// directory, which is what makes the naive open() fail. Embedded textures
// ("*0") have no file at all and are refused here rather than half-handled.
//
// The exact paths are tried first and the index only as a fallback, so a model
// that names its textures correctly is never at the mercy of a same-named file
// somewhere else in the tree.
fs::path resolveTexture(const fs::path& modelDir, const std::string& authored,
                        const TextureIndex& index)
{
    if (authored.empty() || authored.front() == '*')
        return {};
    const fs::path candidate(authored);
    std::error_code ec;
    if (candidate.is_absolute() && fs::is_regular_file(candidate, ec))
        return candidate;
    const fs::path direct = modelDir / candidate;
    if (fs::is_regular_file(direct, ec))
        return direct;
    const fs::path beside = modelDir / candidate.filename();
    if (fs::is_regular_file(beside, ec))
        return beside;

    // Filed somewhere else under the model: "textures/wall.png" named as
    // "wall.png", or a stale absolute path whose file name still holds.
    const auto byName = index.byName.find(lowered(candidate.filename().string()));
    if (byName != index.byName.end())
        return byName->second;

    // Same name, different format. Only reached when nothing matched exactly.
    const auto byStem = index.byStem.find(lowered(candidate.stem().string()));
    if (byStem != index.byStem.end())
        return byStem->second;
    return {};
}

// One PSX-look material per texture. Nearest filtering and wrap addressing are
// this project's look, not a default -- a bilinear-filtered 64x64 texture is
// exactly the wrong result here.
std::string materialBlock(const std::string& name, const std::string& texture)
{
    std::ostringstream out;
    out << "[material.\"" << name << "\"]\n"
        << "shader = \"lit\"\n"
        << "texture = \"" << texture << "\"\n"
        << "filter = \"nearest\"\n"
        << "address = \"repeat\"\n\n";
    return out.str();
}

// Replaces this model's marked block in kit.toml, or appends one. Marked rather
// than appended blindly so reimporting a model after fixing it in Blender
// replaces its pieces instead of leaving a second dead copy behind.
bool rewriteCatalogBlock(const fs::path& kitToml, const std::string& slug,
                         const std::string& block, std::string& error)
{
    std::string text;
    {
        std::ifstream input(kitToml);
        if (!input) {
            error = "cannot read " + kitToml.string();
            return false;
        }
        std::ostringstream buffer;
        buffer << input.rdbuf();
        text = buffer.str();
    }

    const std::string begin = "# BEGIN editor import: " + slug;
    const std::string end = "# END editor import: " + slug;
    const std::size_t from = text.find(begin);
    if (from != std::string::npos) {
        const std::size_t to = text.find(end, from);
        if (to != std::string::npos)
            text.erase(from, to + end.size() - from);
        else
            text.erase(from);
    }
    while (!text.empty() && (text.back() == '\n' || text.back() == ' '))
        text.pop_back();
    text += "\n\n" + begin + "\n" + block + end + "\n";

    std::ofstream output(kitToml);
    if (!output) {
        error = "cannot write " + kitToml.string();
        return false;
    }
    output << text;
    return bool(output);
}

